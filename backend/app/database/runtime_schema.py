def _build_fk_map() -> dict[
    tuple[str, str],
    tuple[str, str],
]:
    mapping = {}

    for (
        child_table,
        child_column,
        parent_table,
        parent_column,
    ) in FOREIGN_KEYS:
        key = (
            child_table,
            child_column,
        )

        if key in mapping:
            raise RuntimeError(
                "Duplicate runtime FK mapping: "
                f"{child_table}.{child_column}"
            )

        mapping[key] = (
            parent_table,
            parent_column,
        )

    return mapping


_FK_MAP = _build_fk_map()


def _build_column(
    table_name: str,
    column_spec: dict,
) -> Column:
    column_name = column_spec["name"]
    type_name = column_spec["type"]

    try:
        factory = _TYPE_FACTORIES[type_name]
    except KeyError as exc:
        raise RuntimeError(
            f"Unsupported runtime SQL type: {type_name}"
        ) from exc

    args = [
        column_name,
        factory(),
    ]

    fk_target = _FK_MAP.get(
        (
            table_name,
            column_name,
        )
    )

    if fk_target is not None:
        parent_table, parent_column = fk_target

        args.append(
            ForeignKey(
                f"{parent_table}.{parent_column}",
                onupdate="RESTRICT",
                ondelete="RESTRICT",
            )
        )

    return Column(
        *args,
        nullable=column_spec["nullable"],
    )


runtime_tables: dict[str, Table] = {}


for table_name, table_spec in TABLE_SPECS.items():
    columns = [
        _build_column(
            table_name,
            column_spec,
        )
        for column_spec in table_spec["columns"]
    ]

    runtime_tables[table_name] = Table(
        table_name,
        runtime_metadata,
        *columns,
        PrimaryKeyConstraint(
            *table_spec["primary_key"],
        ),
    )


def get_runtime_table(
    table_name: str,
) -> Table:
    """Return a runtime table by its exact PostgreSQL name."""
    try:
        return runtime_tables[table_name]
    except KeyError as exc:
        raise KeyError(
            f"Unknown runtime table: {table_name}"
        ) from exc


def validate_runtime_metadata() -> None:
    """Validate table, PK, and FK contracts."""

    if len(TABLE_SPECS) != 51:
        raise RuntimeError(
            f"Expected 51 TABLE_SPECS, found {len(TABLE_SPECS)}"
        )

    if len(runtime_tables) != 51:
        raise RuntimeError(
            f"Expected 51 runtime tables, found {len(runtime_tables)}"
        )

    if len(runtime_metadata.tables) != 51:
        raise RuntimeError(
            "Runtime MetaData table count mismatch: "
            f"{len(runtime_metadata.tables)}"
        )

    if len(FOREIGN_KEYS) != 210:
        raise RuntimeError(
            f"Expected 210 declared FKs, found {len(FOREIGN_KEYS)}"
        )

    actual_fk_count = sum(
        len(table.foreign_keys)
        for table in runtime_tables.values()
    )

    if actual_fk_count != 210:
        raise RuntimeError(
            "SQLAlchemy FK count mismatch: "
            f"expected=210 actual={actual_fk_count}"
        )

    single_pk = 0
    composite_pk = 0

    for table_name, spec in TABLE_SPECS.items():
        table = runtime_tables[table_name]

        expected_pk = list(
            spec["primary_key"]
        )

        actual_pk = [
            column.name
            for column in table.primary_key.columns
        ]

        if actual_pk != expected_pk:
            raise RuntimeError(
                f"Primary-key mismatch for {table_name}: "
                f"expected={expected_pk}, actual={actual_pk}"
            )

        if len(actual_pk) == 1:
            single_pk += 1
        elif len(actual_pk) > 1:
            composite_pk += 1
        else:
            raise RuntimeError(
                f"Table has no PK: {table_name}"
            )

    if single_pk != 48:
        raise RuntimeError(
            f"Expected 48 single PK tables, found {single_pk}"
        )

    if composite_pk != 3:
        raise RuntimeError(
            f"Expected 3 composite PK tables, found {composite_pk}"
        )


validate_runtime_metadata()


